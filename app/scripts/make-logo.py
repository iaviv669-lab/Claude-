"""Generate Ironrow's logo: the barbell mark and the IRONROW wordmark with plate O's.
Letters are outlined from Inter Display Black (SIL Open Font License) so no font is needed at runtime.
Writes src/components/Logo.tsx and public/icon.svg."""
import math, pathlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

def circle(cx, cy, r):
    return f"M{cx - r:.2f} {cy:.2f}a{r:.2f} {r:.2f} 0 1 0 {2 * r:.2f} 0a{r:.2f} {r:.2f} 0 1 0 {-2 * r:.2f} 0z"

def plate(cx, cy, R):
    """Plate face-on: rim (R..0.683R) with two grip slots, hub (0.439R..0.134R). Even-odd fill."""
    s = R / 164
    slot = lambda x: f"M{cx + (x - 256) * s:.2f} {cy - 15 * s:.2f}a{15 * s:.2f} {15 * s:.2f} 0 0 1 {30 * s:.2f} 0v{30 * s:.2f}a{15 * s:.2f} {15 * s:.2f} 0 0 1 {-30 * s:.2f} 0z"
    return circle(cx, cy, R) + circle(cx, cy, 112 * s) + slot(104) + slot(378) + circle(cx, cy, 72 * s) + circle(cx, cy, 22 * s)

def rrect(x, y, w, h, r):
    return (f"M{x + r} {y}h{w - 2 * r}a{r} {r} 0 0 1 {r} {r}v{h - 2 * r}a{r} {r} 0 0 1 {-r} {r}"
            f"h{-(w - 2 * r)}a{r} {r} 0 0 1 {-r} {-r}v{-(h - 2 * r)}a{r} {r} 0 0 1 {r} {-r}z")

def barbell():
    """Side-view barbell, symmetric about x=256: sleeve, big plate, small plate, collar, then the bar."""
    half = [(40, 30, 40, 6), (78, 236, 42, 10), (126, 168, 30, 9), (162, 64, 18, 5)]  # x, height, width, radius
    d = rrect(170, 242, 172, 28, 6)
    for x, h, w, r in half:
        d += rrect(x, 256 - h / 2, w, h, r) + rrect(512 - x - w, 256 - h / 2, w, h, r)
    return d

font = TTFont('/usr/share/fonts/opentype/inter/InterDisplay-Black.otf')
gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
cap = font['OS/2'].sCapHeight  # units
upm = font['head'].unitsPerEm
H = 100.0                     # wordmark cap height in output units
k = H / cap
track = 6.0                   # gap between letters
parts, x = [], 0.0
for ch in 'IRONROW':
    if ch == 'O':
        R = H / 2 * 1.02
        parts.append(plate(x + R, H / 2, R)); x += 2 * R + track; continue
    g = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    gs[g].draw(TransformPen(pen, (k, 0, 0, -k, x, H)))
    # trim left side bearing so spacing is set by `track`
    parts.append(pen.getCommands()); x += hmtx[g][0] * k + track - 2
width = x - track
word_d = ' '.join(parts)
mark_d = barbell()

tsx = f'''// Generated by scripts/make-logo.py. Do not edit by hand.
// Mark: a side-view barbell. Wordmark: IRONROW with plate O's,
// letters outlined from Inter Display Black (SIL OFL).
export const MARK_PATH = '{mark_d}';
export const WORDMARK_PATH = '{word_d}';
export const WORDMARK_VIEWBOX = '0 0 {width:.1f} {H:.0f}';

export function Mark({{ size = 24, className = '' }}: {{ size?: number; className?: string }}) {{
  return <svg width={{size}} height={{size}} viewBox="0 0 512 512" className={{className}} aria-hidden><path d={{MARK_PATH}} fill="currentColor" /></svg>;
}}

export function Wordmark({{ height = 20, className = '' }}: {{ height?: number; className?: string }}) {{
  return <svg height={{height}} viewBox={{WORDMARK_VIEWBOX}} className={{className}} role="img" aria-label="Ironrow"><path d={{WORDMARK_PATH}} fill="currentColor" fillRule="evenodd" /></svg>;
}}

/** The app icon: the barbell on the dark purple gradient. */
export function AppIcon({{ size = 48, className = '' }}: {{ size?: number; className?: string }}) {{
  return (
    <svg width={{size}} height={{size}} viewBox="0 0 512 512" className={{className}} aria-hidden>
      <defs><linearGradient id="ir-g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stopColor="#5a2fd6" /><stop offset=".55" stopColor="#2a1173" /><stop offset="1" stopColor="#0e0826" /></linearGradient></defs>
      <rect width="512" height="512" rx="112" fill="url(#ir-g)" />
      <path d={{MARK_PATH}} fill="#ffffff" />
    </svg>
  );
}}
'''
pathlib.Path('src/components/Logo.tsx').write_text(tsx)
icon = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#5a2fd6"/><stop offset=".55" stop-color="#2a1173"/><stop offset="1" stop-color="#0e0826"/></linearGradient></defs><rect width="512" height="512" rx="112" fill="url(#g)"/><path d="{mark_d}" fill="#ffffff"/></svg>'''
pathlib.Path('public/icon.svg').write_text(icon)
print('wordmark width', round(width, 1), 'paths', len(word_d))
